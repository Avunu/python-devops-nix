class TestRoundTrip(CheckoutCase):
    def test_sync_then_check_is_clean_and_idempotent(self):
        self.synced()
        before = self.snapshot()
        code, _, err = self.fn("sync", "--write")
        self.assertEqual(code, 0, err)
        self.assertEqual(before, self.snapshot(), "a second --write changed bytes")

    def test_new_checkout_gets_the_managed_files(self):
        self.synced()
        for path in (
            "flake.nix",
            ".envrc",
            ".editorconfig",
            "committed.toml",
            "tools/pyproject.toml",
            "tools/uv.lock",
            ".git-blame-ignore-revs",
            ".github/dependabot.yml",
            ".github/workflows/ci.yml",
            "CONTRIBUTING.md",
        ):
            self.assertTrue((self.root / path).is_file(), path)
        self.assertTrue(self.read(".envrc").startswith("# stub-nix:managed"))
        self.assertIn(
            "# stub-nix:managed — generated by stub-nix (`stub-init --sync`); edit only"
            " inside the stub-nix:local region.\n",
            self.read("flake.nix"),
        )
        self.assertTrue(
            self.read("committed.toml").startswith(
                "# stub-nix:managed — generated by stub-nix (`stub-init --sync`); do"
                " not edit.\n"
            )
        )
        doc = tomllib.loads(self.read("pyproject.toml"))
        self.assertEqual(doc["tool"]["ruff"]["lint"]["select"], ["F", "E", "W", "I"])
        self.assertEqual(doc["tool"]["coverage"]["report"]["fail_under"], 50)
        self.assertTrue(doc["tool"]["coverage"]["report"]["show_missing"])

    def test_the_writes_are_staged_not_committed(self):
        code, _, err = self.fn("sync", "--write")
        self.assertEqual(code, 0, err)
        staged = git(self.root, "diff", "--cached", "--name-only").split()
        self.assertIn("flake.nix", staged)
        self.assertIn("pyproject.toml", staged)
        self.assertEqual(git(self.root, "log", "--format=%s").split(), ["test"])

    def test_editing_a_managed_file_is_drift_with_a_diff(self):
        self.synced()
        self.write(
            "committed.toml",
            self.read("committed.toml").replace(
                "subject_length = 100", "subject_length = 72"
            ),
        )
        code, out = self.check()
        self.assertEqual(code, 1, out)
        self.assertIn("committed.toml (whole): differs from the rendered file", out)
        self.assertIn("--- current", out)
        self.assertIn("-subject_length = 72", out)
        self.assertIn("+subject_length = 100", out)
        self.assertIn("stub-nix: 1 file(s) drifted — run `stub-init --sync`", out)

    def test_check_json_format(self):
        self.synced()
        self.write(".envrc", "use flake\n")
        code, out, _ = self.fn("sync", "--check", "--format", "json")
        self.assertEqual(code, 1)
        doc = json.loads(out)
        self.assertEqual(
            list(doc), ["status", "stub_nix", "files", "profile", "modules"]
        )
        self.assertEqual(doc["status"], "drift")
        self.assertEqual(doc["stub_nix"], {"rev": "a" * 40, "version": "1.0.0"})
        self.assertEqual([f["path"] for f in doc["files"]], [".envrc"])
        self.assertEqual(
            list(doc["files"][0]), ["path", "strategy", "module", "problem", "diff"]
        )
        self.assertEqual(doc["files"][0]["module"], "dev-shell")
        self.assertEqual(doc["profile"]["name"], "recommended@1.0")
        self.assertEqual(list(doc["modules"]), list(STUB.modules.names))

    def test_check_github_format(self):
        self.synced()
        self.write(".envrc", "use flake\n")
        code, out, _ = self.fn("sync", "--check", "--format", "github")
        self.assertEqual(code, 1)
        self.assertIn("::stop-commands::", out)
        self.assertIn("::error file=.envrc::differs from the rendered file", out)

    def test_only(self):
        self.synced()
        self.write(".envrc", "use flake\n")
        self.write("committed.toml", "x = 1\n")
        code, _, err = self.fn("sync", "--write", "--only", ".envrc")
        self.assertEqual(code, 0, err)
        self.assertTrue(self.read(".envrc").startswith("# stub-nix:managed"))
        self.assertEqual(self.read("committed.toml"), "x = 1\n")
        code, out = self.check()
        self.assertEqual(code, 1, out)
        code, out, _ = self.fn("sync", "--check", "--only", ".envrc,flake.nix")
        self.assertEqual(code, 0, out)

    def test_dry_run_writes_nothing(self):
        before = self.snapshot()
        code, out, err = self.fn("sync", "--write", "--dry-run")
        self.assertEqual(code, 0, err)
        self.assertIn("flake.nix (whole): missing", out)
        self.assertIn("+++ rendered", out)
        self.assertEqual(before, self.snapshot())

    def test_not_a_checkout_is_exit_3(self):
        (self.root / "pyproject.toml").unlink()
        code, out = self.check()
        self.assertEqual(code, 3, out)
        self.assertIn("pyproject.toml does not exist", out)

    def test_not_opted_in_is_exit_2_with_the_hint(self):
        self.write("pyproject.toml", '[project]\nname = "demo_unit"\n')
        self.commit()
        for argv in (("--check",), ("--write",)):
            code, out, err = self.fn("sync", *argv)
            self.assertEqual(code, 2, out + err)
            self.assertIn("has not opted in to stub-nix standards", out + err)
        self.assertEqual(git(self.root, "status", "--porcelain"), "")


class TestCheckReportsRaisedErrors(CheckoutCase):
    """json and github stay a report when the plan itself can't be built."""

    def json_check(self, cwd=None) -> tuple[int, dict]:
        code, out, _ = self.fn("sync", "--check", "--format", "json", cwd=cwd)
        return code, json.loads(out)

    def test_an_invalid_table(self):
        self.synced()
        self.table("nope = 1\n")
        code, doc = self.json_check()
        self.assertEqual(code, 2)
        self.assertEqual(doc["status"], "invalid")
        self.assertEqual(doc["files"][0]["path"], "pyproject.toml")
        self.assertIn("nope", doc["files"][0]["problem"])
        self.assertEqual(doc["stub_nix"], {"rev": "a" * 40, "version": "1.0.0"})
        code, out, _ = self.fn("sync", "--check", "--format", "github")
        self.assertEqual(code, 2)
        self.assertIn("::error file=pyproject.toml::", out)

    def test_malformed_region_names_its_file(self):
        self.synced()
        self.write(
            ".editorconfig",
            self.read(".editorconfig")
            + "# stub-nix:local-begin bogus\n# stub-nix:local-end bogus\n",
        )
        code, doc = self.json_check()
        self.assertEqual(code, 2)
        self.assertEqual(doc["status"], "invalid")
        self.assertEqual(doc["files"][0]["path"], ".editorconfig")

    def test_not_a_repository(self):
        with tempfile.TemporaryDirectory() as bare:
            code, doc = self.json_check(Path(bare))
        self.assertEqual(code, 3)
        self.assertEqual(doc["status"], "error")
        self.assertEqual(len(doc["files"]), 1)

    def test_text_keeps_the_one_line_error(self):
        with tempfile.TemporaryDirectory() as bare:
            code, out, err = run_cli(STUB, "sync", "--check", cwd=Path(bare))
        self.assertEqual(code, 3)
        self.assertEqual(out, "")
        self.assertIn("stub-nix sync:", err)

    def test_a_crash_is_exit_3_in_a_report(self):
        with mock.patch.object(engine, "build", side_effect=KeyError("boom")):
            code, doc = self.json_check()
        self.assertEqual(code, 3)
        self.assertIn("internal error: KeyError", doc["files"][0]["problem"])


