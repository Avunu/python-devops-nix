"""The stub product: identity, markers, engine and pins (the stage-1 skeleton).

Its hooks arrive with the configuration and the engine (DESIGN §12, stages 2 and 3);
until then each one says so when called.
"""

from importlib.resources import files
from pathlib import Path
from types import MappingProxyType

from standards_core.product import (
    CORE_MODULES,
    Engine,
    Hooks,
    Identity,
    Markers,
    Modules,
    Pins,
    Product,
)
from stub_nix_tools import __version__


def _not_yet(*args, **kwargs):
    raise NotImplementedError("the stub product's hooks come with a later stage")


IDENTITY = Identity(
    name="stub-nix",
    cli="stub-nix",
    distribution="stub-nix-tools",
    version=__version__,
    table="stub-nix",
    env_prefix="STUB_NIX",
    report_key="stub_nix",
    sync_command="stub-init --sync",
    opt_in_hint=(
        "this checkout has not opted in to stub-nix standards; run "
        "stub-init --sync --standards minimal|recommended|github:<owner>/<repo>"
    ),
    docs_url="https://example.org/stub-nix/docs",
)

MARKERS = Markers(
    managed="stub-nix:managed",
    header="stub-nix:managed — generated by stub-nix (`stub-init --sync`);",
    header_local="edit only inside the stub-nix:local region.",
    local="stub-nix:local",
    block_begin=">>> stub-nix: {name} (managed) >>>",
    block_end="<<< stub-nix: {name} (managed) <<<",
    html_begin="<!-- stub-nix:begin {name} -->",
    html_end="<!-- stub-nix:end {name} -->",
)

ENGINE = Engine(
    flake_input="stub-nix",
    repo="example/stub-nix",
    release_branch="release-{major}",
    url_key="dev-shell.stub-nix-url",
    install_spec=(
        "stub-nix-tools @ git+https://github.com/{owner}/{repo}@{rev}"
        "#subdirectory=py/stub_nix_tools"
    ),
    caller_stem="stub-*",
    init_app="stub-init",
)

# The inputs the stub engine pins for every checkout, read only through its node.
PINS = Pins(
    dir=".dev-dist/pins",
    engine_pinned=MappingProxyType(
        {
            "lint-rules": ("example", "lint-rules"),
            "registry": ("example", "registry"),
            "pilot": ("example", "pilot"),
        }
    ),
)

PRODUCT = Product(
    identity=IDENTITY,
    markers=MARKERS,
    engine=ENGINE,
    pins=PINS,
    modules=Modules(names=CORE_MODULES),
    data_root=Path(str(files("stub_nix_tools").joinpath("data"))),
    hooks=Hooks(
        load_checkout=_not_yet,
        discover=_not_yet,
        gates=_not_yet,
        template_globals=_not_yet,
    ),
)
