"""The kit stub product: identity, markers, engine and pins (the stage-1 skeleton).

A ``bundle`` checkout has no root ``pyproject.toml``, so the config file is optional
here (``config_required = False``), and managed JSON is written in prettier's form.
Its hooks arrive with later stages (DESIGN §12); until then each one says so.
"""

from importlib.resources import files
from pathlib import Path

from kit_nix_tools import __version__
from standards_core.product import (
    CORE_MODULES,
    Engine,
    Hooks,
    Identity,
    JsonStyle,
    Markers,
    Modules,
    Pins,
    Product,
)


def _not_yet(*args, **kwargs):
    raise NotImplementedError("the kit product's hooks come with a later stage")


IDENTITY = Identity(
    name="kit-nix",
    cli="kit-nix",
    distribution="kit-nix-tools",
    version=__version__,
    table="kit-nix",
    env_prefix="KIT_NIX",
    report_key="kit_nix",
    sync_command="kit-init --sync",
    opt_in_hint=(
        "this checkout has not opted in to kit-nix standards; run "
        "kit-init --sync --standards minimal|recommended|github:<owner>/<repo>"
    ),
    docs_url="https://example.org/kit-nix/docs",
    config_required=False,
)

MARKERS = Markers(
    managed="kit-nix:managed",
    header="kit-nix:managed — generated by kit-nix (`kit-init --sync`);",
    header_local="edit only inside the kit-nix:local region.",
    local="kit-nix:local",
    block_begin=">>> kit-nix: {name} (managed) >>>",
    block_end="<<< kit-nix: {name} (managed) <<<",
    html_begin="<!-- kit-nix:begin {name} -->",
    html_end="<!-- kit-nix:end {name} -->",
)

ENGINE = Engine(
    flake_input="kit-nix",
    repo="example/kit-nix",
    release_branch="release-{major}",
    url_key="dev-shell.kit-nix-url",
    install_spec=(
        "kit-nix-tools @ git+https://github.com/{owner}/{repo}@{rev}"
        "#subdirectory=py/kit_nix_tools"
    ),
    caller_stem="kit-*",
    init_app="kit-init",
)

PINS = Pins(dir=".dev-dist/pins")

PRODUCT = Product(
    identity=IDENTITY,
    markers=MARKERS,
    engine=ENGINE,
    pins=PINS,
    modules=Modules(names=CORE_MODULES),
    data_root=Path(str(files("kit_nix_tools").joinpath("data"))),
    hooks=Hooks(
        load_checkout=_not_yet,
        discover=_not_yet,
        gates=_not_yet,
        template_globals=_not_yet,
    ),
    json_style=JsonStyle(indent="  ", width=80, trailing_commas="none"),
)
