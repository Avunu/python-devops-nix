_UNIT = re.compile(r"[^/]+/__unit__\.toml")
_SERIES = re.compile(r"\d+\.0")
_SERIES_VERSION = re.compile(r"(\d+\.0)\.(\d+)\.(\d+)\.(\d+)")


def _units(tracked: list[str]) -> list[str]:
    return sorted(p for p in tracked if _UNIT.fullmatch(p))


def shape(checkout: Checkout, table: Mapping[str, Any]) -> str:
    """``bundle`` or ``workspace`` (``""`` when the tracked files say neither)."""
    if table.get("shape"):
        return str(table["shape"])
    if _units(checkout.tracked):
        return "bundle"
    if "core" in checkout.tracked or "units.txt" in checkout.tracked:
        return "workspace"
    return ""


def _read(root: Path, rel: str) -> str:
    try:
        return (root / rel).read_text()
    except (OSError, UnicodeDecodeError):
        return ""


def series(checkout: Checkout) -> str:
    """The series: the units' versions, else ``.kit-series``, else a ``<n>.0`` branch."""
    for rel in _units(checkout.tracked):
        try:
            version = tomllib.loads(_read(checkout.root, rel)).get("version", "")
        except tomllib.TOMLDecodeError:
            continue
        m = _SERIES_VERSION.fullmatch(str(version))
        if m:
            return m[1]
    if ".kit-series" in checkout.tracked:
        text = _read(checkout.root, ".kit-series").strip()
        if _SERIES.fullmatch(text):
            return text
    try:
        branch = repo.git(checkout.root, "rev-parse", "--abbrev-ref", "HEAD").strip()
    except EnvError:
        return ""
    return branch if _SERIES.fullmatch(branch) else ""


def _table(checkout: Checkout) -> Mapping[str, Any]:
    tool = checkout.config.get("tool", {})
    table = tool.get("kit-nix") if isinstance(tool, dict) else None
    return table if isinstance(table, dict) else {}


class KitSeries:
    """``kit-series``: ``<series>.x.y.z``; ``!`` raises x, feat y, fix and perf z."""

    name = "kit-series"

    def valid(self, version: str, cfg: Mapping[str, Any], facts: Mapping) -> str | None:
        m = _SERIES_VERSION.fullmatch(version)
        if not m:
            return f"{version} is not <series>.<x>.<y>.<z>"
        want = facts.get("series") or cfg.get("series")
        if want and m[1] != want:
            return f"{version} is not on series {want}"
        return None

    def bump(
        self, version: str, level: Level, cfg: Mapping[str, Any], facts: Mapping
    ) -> str:
        m = _SERIES_VERSION.fullmatch(version)
        if not m:
            raise ConfigError(f"{version} is not <series>.<x>.<y>.<z>")
        x, y, z = (int(g) for g in m.groups()[1:])
        if level == "major":
            x, y, z = x + 1, 0, 0
        elif level == "minor":
            y, z = y + 1, 0
        else:
            z += 1
        return f"{m[1]}.{x}.{y}.{z}"

    def message_problems(
        self, text: str, cfg: Mapping[str, Any], facts: Mapping
    ) -> list[str]:
        return []

    def tag_problem(
        self, tag: str, cfg: Mapping[str, Any], facts: Mapping
    ) -> str | None:
        return None


BRANCHING = MappingProxyType(
    {
        "develop+series": Branching(
            name="develop+series",
            flow="post-merge-bump",
            integration=lambda cfg: "develop",
            release_branch=lambda cfg, facts: (
                facts.get("series") or cfg.get("series") or ""
            ),
            release_pattern="refs/heads/*.0",
            release_label="*.0",
        ),
    }
)


def load_checkout(root: Path) -> Checkout:
    return default_load_checkout(PRODUCT, root)


def discover(
    checkout: Checkout, cfg: Mapping[str, Any], modules: Mapping[str, bool]
) -> dict[str, Any]:
    return {
        "shape": shape(checkout, _table(checkout)),
        "series": cfg.get("series") or series(checkout),
        "units": [p.split("/", 1)[0] for p in _units(checkout.tracked)],
        "package_json": "package.json" in checkout.tracked,
    }


def gates(
    modules: Mapping[str, bool], cfg: Mapping[str, Any], facts: Mapping[str, Any]
) -> list[str]:
    ci = modules.get("ci", False)
    on = {
        "pr-policy": ci and modules.get("commits", False),
        "lint": ci,
        "test": ci and modules.get("tests", False),
    }
    return [g for g in PRODUCT.ci.gates if on[g]]


def template_globals(checkout: Checkout, resolved: Any, ctx: Any) -> dict[str, Any]:
    return {"shape": ctx["discover"]["shape"], "series": ctx["discover"]["series"]}


def derive(cfg: dict[str, Any], checkout: Checkout | None) -> None:
    """The series default, from the same sources discovery reads."""
    if "series" not in cfg and checkout is not None:
        found = series(checkout)
        if found:
            cfg["series"] = found


# --- package.json and tools/pyproject.toml: the managed keys -------------------------


def _floors(ctx: Any, kind: str) -> dict[str, str]:
    return dict(ctx.floors.get(kind, {}))


def package_groups(ctx: Any) -> dict[str, list[tuple[tuple[str, ...], Any]]]:
    pins = _floors(ctx, "npm")
    return {
        "editor": [
            (("devDependencies", pkg), floors.caret(v))
            for pkg, v in sorted(pins.items())
        ]
    }


def package_on(ctx: Any, group: str) -> bool:
    """The pins are managed in a ``package.json`` the checkout has."""
    return bool(ctx.modules.get(group)) and bool(ctx.discover.get("package_json"))


def package_reconcile(ctx: Any, path: tuple[str, ...], have: Any, rendered: Any) -> Any:
    """A floor: a caret range at or above the rendered one stays."""
    if not isinstance(have, str):
        return rendered
    return have if floors.range_ok(have, rendered.lstrip("^")) else rendered


PACKAGE = JsonGroupsHandler(
    "kit-package",
    JsonGroups(groups=package_groups, on=package_on, reconcile=package_reconcile),
)

_PIN = re.compile(r"(?P<name>[A-Za-z0-9_.-]+)==(?P<version>\S+)")


def tools_groups(ctx: Any) -> dict[str, list[tuple[tuple[str, ...], Any]]]:
    pins = _floors(ctx, "uv")
    deps = [f"ruff=={pins['ruff']}"]
    if ctx.modules.get("tests"):
        deps.append(f"pytest=={pins['pytest']}")
    return {
        "python-lint": [
            (("project", "name"), "kit-tools"),
            (("project", "version"), "0"),
            (("project", "requires-python"), ">=3.11"),
            (("project", "dependencies"), deps),
            (("tool", "uv", "package"), False),
        ],
        "tests": [
            (("tool", "coverage", "run", "branch"), True),
            (("tool", "coverage", "report", "show_missing"), True),
        ],
    }


def tools_on(ctx: Any, group: str) -> bool:
    return bool(ctx.modules.get(group))


def tools_reconcile(ctx: Any, path: tuple[str, ...], have: Any, rendered: Any) -> Any:
    """The exact pins are floors: a pin raised by hand stays, per package."""
    if path != ("project", "dependencies") or not isinstance(have, list):
        return rendered
    raised = {}
    for dep in have:
        m = _PIN.fullmatch(str(dep))
        if m:
            raised[m["name"]] = dep
    out = []
    for dep in rendered:
        m = _PIN.fullmatch(dep)
        mine = raised.get(m["name"]) if m else None
        if mine and floors.at_least(_PIN.fullmatch(mine)["version"], m["version"]):
            out.append(mine)
        else:
            out.append(dep)
    return out


def tools_seeds(ctx: Any, doc: dict) -> list[tuple[tuple[str, ...], Any]]:
    """``fail_under`` from ``tests.coverage.initial-floor``, once."""
    if not ctx.modules.get("tests"):
        return []
    floor = ctx.cfg["tests"]["coverage"]["initial-floor"]
    return [(("tool", "coverage", "report", "fail_under"), floor)]


TOOLS = TomlMergeHandler(
    "kit-tools",
    TomlGroups(
        groups=tools_groups,
        on=tools_on,
        canon_tables=(
            "project",
            "tool.uv",
            "tool.coverage.run",
            "tool.coverage.report",
        ),
        reconcile=tools_reconcile,
        seeds=tools_seeds,
    ),
)


# --- whole-repo checks ----------------------------------------------------------------

_SUBMODULE = re.compile(r"^\[submodule \"(?P<name>[^\"]+)\"\]\s*$")
_BRANCH = re.compile(r"^\s*branch\s*=\s*(?P<branch>\S+)\s*$")


def submodule_branches(text: str) -> dict[str, str]:
    """Each submodule of a ``.gitmodules`` text and its ``branch`` (``""`` for none)."""
    out: dict[str, str] = {}
    name = None
    for line in text.splitlines():
        if m := _SUBMODULE.match(line):
            name = m["name"]
            out[name] = ""
        elif name is not None and (m := _BRANCH.match(line)):
            out[name] = m["branch"]
    return out


def checks(plan: Any) -> list[Item]:
    """Under ``hygiene``: every unit has a ``README.md``; every submodule follows the
    series (``branch = <series>``)."""
    if not plan.ctx.modules.get("hygiene"):
        return []
    tracked = set(plan.checkout.tracked)
    out = []
    for unit in plan.ctx.discover["units"]:
        if f"{unit}/README.md" not in tracked:
            out.append(
                Item(
                    f"{unit}/README.md",
                    "check",
                    None,
                    None,
                    "missing: every unit has a README.md",
                    DRIFT,
                    module="hygiene",
                )
            )
    if ".gitmodules" in tracked:
        series_ = plan.ctx.discover["series"]
        text = _read(plan.root, ".gitmodules")
        for name, branch in sorted(submodule_branches(text).items()):
            if branch != series_:
                out.append(
                    Item(
                        ".gitmodules",
                        "check",
                        text,
                        text,
                        f"submodule {name} has branch = {branch or '(none)'}, not the"
                        f" series {series_}",
                        DRIFT,
                        module="hygiene",
                    )
                )
    return out


# --- releases ---------------------------------------------------------------------------

_UNIT_VERSION = re.compile(r'^version\s*=\s*"(?P<version>[^"]*)"', re.MULTILINE)


class UnitManifest:
    """``unit-manifest``: each unit's version is ``version = "…"`` in
    ``<unit>/__unit__.toml``."""

    name = "unit-manifest"
    commit_subject = "chore(release): bump {units}"

    def units(self, root: Path, ctx: Any) -> list[ReleaseUnit]:
        tracked = repo.ls_files(root)
        return [
            ReleaseUnit(p.split("/", 1)[0], p.split("/", 1)[0] + "/", p)
            for p in _units(tracked)
        ]

    def read_version(self, text: str, unit: ReleaseUnit) -> str | None:
        m = _UNIT_VERSION.search(text)
        return m["version"] if m else None

    def write_version(self, text: str, unit: ReleaseUnit, version: str) -> str:
        m = _UNIT_VERSION.search(text)
        if m is None:
            raise ConfigError(f"{unit.version_file} has no version")
        return text[: m.start("version")] + version + text[m.end("version") :]

    def exempt(self, unit: ReleaseUnit, path: str) -> bool:
        rel = path.removeprefix(unit.path)
        return rel == "README.md" or rel.startswith(("tests/", "i18n/"))


