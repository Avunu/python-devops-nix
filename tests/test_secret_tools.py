KEYS = Path(sys.argv.pop(2)).resolve()
PYTHON_DIR = Path(sys.argv.pop(1)).resolve()
sys.path.insert(0, str(PYTHON_DIR))

import secret_tools as st

ALICE = (KEYS / "alice.pub").read_text().splitlines()[0]
BOB = (KEYS / "bob.pub").read_text().splitlines()[0]
REL = "secrets/backup-access.age"


def tool(name: str) -> str:
    path = shutil.which(name)
    if path is None:
        raise unittest.SkipTest(f"{name} is not on PATH")
    return path


class RulesTest(unittest.TestCase):
    def test_render_matches_the_jq_renderer_it_replaces(self):
        # Byte for byte what lib.secrets.tools' jq program wrote.
        got = st.render_rules(
            {"secrets/a.age": [ALICE, BOB], "secrets/s/b.age": [ALICE]},
            "/w/proj",
            "stub-nix",
        )
        self.assertEqual(
            got,
            "# Generated by stub-nix. Do not edit; do not commit.\n"
            "{\n"
            f'  "/w/proj/secrets/a.age".publicKeys = ["{ALICE}" "{BOB}"];\n'
            f'  "/w/proj/secrets/s/b.age".publicKeys = ["{ALICE}"];\n'
            "}\n",
        )

    def test_nix_string_escapes_what_nix_would_read(self):
        self.assertEqual(st.nix_string('a"b\\c'), '"a\\"b\\\\c"')
        self.assertEqual(st.nix_string("${x} $y"), '"\\${x} $y"')
        self.assertEqual(st.nix_string("a\nb\tc"), '"a\\nb\\tc"')
        self.assertEqual(st.nix_string("ünï"), '"ünï"')


class EnvFileTest(unittest.TestCase):
    VALUES: ClassVar[dict[str, str]] = {
        "BACKUPS_URL": "https://s3.example.invalid",
        "BACKUPS_ACCESS_KEY": "AK",
        "BACKUPS_SECRET_KEY": "s/e+c'r$et`x\" \\n",
        "BACKUPS_BUCKET": "b",
        "BACKUPS_PREFIX": "odoo/prod",
    }

    def test_round_trip(self):
        text = st.render_env(self.VALUES, "stub restore")
        self.assertTrue(
            text.startswith(
                "# Written by setup-backup-access. Sourced by stub restore.\n"
            )
        )
        self.assertEqual(st.parse_env(text), self.VALUES)

    def test_the_shell_reads_what_it_writes(self):
        text = st.render_env(self.VALUES, "stub restore")
        with tempfile.NamedTemporaryFile("w", suffix=".env") as f:
            f.write(text)
            f.flush()
            out = subprocess.run(
                ["bash", "-c", 'set -a; . "$1"; env -0', "-", f.name],
                check=True,
                capture_output=True,
                text=True,
                env={"PATH": os.environ["PATH"]},
            ).stdout
        env = dict(item.split("=", 1) for item in out.split("\0") if "=" in item)
        for key, value in self.VALUES.items():
            self.assertEqual(env[key], value, key)

    def test_an_empty_prefix_is_left_out(self):
        text = st.render_env({**self.VALUES, "BACKUPS_PREFIX": ""}, "r")
        self.assertNotIn("BACKUPS_PREFIX", text)
        self.assertEqual(len(text.splitlines()), 5)

    def test_a_hand_written_file_is_read_as_written(self):
        got = st.parse_env(
            "# comment\nBACKUPS_URL=https://x\nBACKUPS_BUCKET='b'\nOTHER=1\n"
            "BACKUPS_PREFIX=\nBACKUPS_SECRET_KEY=a b\n"
        )
        self.assertEqual(
            got,
            {
                "BACKUPS_URL": "https://x",
                "BACKUPS_BUCKET": "b",
                "BACKUPS_PREFIX": "",
                "BACKUPS_SECRET_KEY": "a b",
            },
        )


class ConfigTest(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp)
        self.rules = self.tmp / "rules.json"
        self.rules.write_text(json.dumps({REL: [ALICE]}))

    def data(self, **extra):
        return {
            "label": "stub-nix",
            "option": "stub-nix.secrets",
            "relDir": "secrets",
            "rules": str(self.rules),
            "identityPaths": ["$HOME/.ssh/id_ed25519"],
            "secretNames": ["backup-access"],
            "agenix": "agenix",
            "agecheck": "agecheck",
            "rage": "rage",
            "git": "git",
            **extra,
        }

    def test_loads(self):
        cfg = st.Config.from_json(self.data())
        self.assertEqual(cfg.rules, {REL: [ALICE]})
        self.assertIsNone(cfg.backup_access)
        cfg = st.Config.from_json(
            self.data(
                backupAccess={
                    "restoreCommand": "r",
                    "bucketExample": "b",
                    "fetch": "/f",
                    "verifyListing": "/v",
                }
            )
        )
        self.assertEqual(cfg.backup_access.restore_command, "r")

    def test_unknown_and_missing_keys_fail(self):
        with self.assertRaisesRegex(ValueError, "unknown key.*colour"):
            st.Config.from_json(self.data(colour=1))
        data = self.data()
        del data["agenix"]
        with self.assertRaisesRegex(ValueError, "missing key.*agenix"):
            st.Config.from_json(data)
        with self.assertRaisesRegex(ValueError, "backupAccess: missing"):
            st.Config.from_json(self.data(backupAccess={"fetch": "/f"}))

    def test_main_reports_a_bad_configuration(self):
        path = self.tmp / "c.json"
        path.write_text(json.dumps(self.data(colour=1)))
        self.assertEqual(st.main(["rules", "/w"], config=path), 2)
        self.assertEqual(st.main(["frobnicate"], config=path), 2)

    def test_identities(self):
        home = self.tmp / "home"
        (home / ".ssh").mkdir(parents=True)
        (home / ".ssh" / "id_ed25519").write_text("k")
        cfg = st.Config.from_json(
            self.data(identityPaths=["$HOME/.ssh/id_ed25519", "${HOME}/.ssh/id_rsa"])
        )
        old = os.environ.get("HOME")
        os.environ["HOME"] = str(home)
        try:
            candidates, readable = st.identities(cfg)
        finally:
            os.environ["HOME"] = old or ""
        self.assertEqual(candidates, [f"{home}/.ssh/id_ed25519", f"{home}/.ssh/id_rsa"])
        self.assertEqual(readable, [f"{home}/.ssh/id_ed25519"])
        self.assertEqual(st.agenix_identity_args(["a", "b"]), ["-i", "a", "b"])
        self.assertEqual(st.rage_identity_args(["a", "b"]), ["-i", "a", "-i", "b"])


class FakeTerminal:
    """Answers prompts from a script, and records what was shown."""

    def __init__(self, answers=(), confirms=()):
        self.answers = list(answers)
        self.confirms = list(confirms)
        self.asked = []
        self.questions = []
        self.lines = []

    def say(self, message="", style=None):
        self.lines.append(message)

    note = error = detail = say

    def panel(self, lines, colour):
        self.lines.extend(lines)

    def ask(self, header, example="", current="", *, password=False, hint=""):
        self.asked.append((header, current, password, hint))
        answer = self.answers.pop(0)
        return current if answer is None else answer

    def confirm(self, question):
        self.questions.append(question)
        return self.confirms.pop(0)

    def text(self):
        return "\n".join(self.lines)


class SetupFlowTest(unittest.TestCase):
    """setup-backup-access end to end, but for the terminal."""

    def setUp(self):
        self.agenix = tool("agenix")
        self.rage = tool("rage")
        self.git = tool("git")
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp)
        self.root = self.tmp / "project"
        (self.root / "secrets").mkdir(parents=True)
        self.env = {
            "HOME": str(self.tmp / "home"),
            "GIT_CONFIG_GLOBAL": str(self.tmp / "gitconfig"),
            "GIT_CONFIG_SYSTEM": "/dev/null",
            "REPO_ROOT": str(self.root),
        }
        (self.tmp / "home" / ".ssh").mkdir(parents=True)
        for name in ("alice", "bob"):
            dest = self.tmp / name
            shutil.copy(KEYS / name, dest)
            dest.chmod(0o600)
        self.saved_env = dict(os.environ)
        os.environ.update(self.env)
        self.saved_cwd = os.getcwd()
        subprocess.run([self.git, "init", "-q", str(self.root)], check=True)

        rules = self.tmp / "rules.json"
        rules.write_text(json.dumps({REL: [ALICE]}))
        agecheck = self.tmp / "agecheck"
        agecheck.write_text(
            f'#!/bin/sh\nexec {sys.executable} -I {PYTHON_DIR}/agecheck.py "$@"\n'
        )
        agecheck.chmod(0o755)
        self.seen = self.tmp / "verify-env"
        self.verify = self.tmp / "verify"
        self.verify.write_text(
            f"#!{tool('bash')}\n"
            f'env | grep -E "^(BACKUPS_|FETCH=)" | sort > {self.seen}\n'
            'if [ "$BACKUPS_BUCKET" = bad ]; then echo "Access Denied." >&2; exit 1; fi\n'
            'echo "2 backup(s) found; newest is 2026-10-02"\n'
        )
        self.verify.chmod(0o755)
        self.cfg = st.Config.from_json(
            {
                "label": "stub-nix",
                "option": "stub-nix.secrets",
                "relDir": "secrets",
                "rules": str(rules),
                "identityPaths": ["$HOME/.ssh/id_ed25519", "$HOME/.ssh/missing"],
                "secretNames": ["backup-access"],
                "agenix": self.agenix,
                "agecheck": str(agecheck),
                "rage": self.rage,
                "git": self.git,
                "backupAccess": {
                    "restoreCommand": "stub restore",
                    "bucketExample": "my-stub-backups",
                    "fetch": "/stub/fetch",
                    "verifyListing": str(self.verify),
                },
            }
        )

    def tearDown(self):
        os.chdir(self.saved_cwd)
        os.environ.clear()
        os.environ.update(self.saved_env)

    def key(self, name="alice"):
        shutil.copy(self.tmp / name, self.tmp / "home" / ".ssh" / "id_ed25519")
        (self.tmp / "home" / ".ssh" / "id_ed25519").chmod(0o600)

    def run_setup(self, ui, interactive=True):
        return st.cmd_setup_backup_access(
            self.cfg, [], ui=ui, is_interactive=lambda: interactive
        )

    def decrypt(self, identity="alice"):
        return subprocess.run(
            [
                self.rage,
                "--decrypt",
                "-i",
                str(self.tmp / identity),
                str(self.root / REL),
            ],
            check=True,
            capture_output=True,
            text=True,
        ).stdout

    def tracked(self):
        return (
            subprocess.run(
                [self.git, "-C", str(self.root), "ls-files", "--error-unmatch", REL],
                check=False,
                capture_output=True,
            ).returncode
            == 0
        )

    def test_without_a_terminal_it_refuses_and_never_prompts(self):
        ui = FakeTerminal()
        self.assertEqual(self.run_setup(ui, interactive=False), 1)
        self.assertEqual(ui.asked, [])
        self.assertFalse((self.root / REL).exists())

    def test_without_a_readable_key_it_says_which_it_tried(self):
        ui = FakeTerminal()
        self.assertEqual(self.run_setup(ui), 1)
        self.assertIn(f"{self.env['HOME']}/.ssh/id_ed25519", ui.text())
        self.assertIn("stub-nix.secrets.identityPaths", ui.text())
        self.assertEqual(ui.asked, [])

    def test_first_run_writes_stages_and_checks(self):
        self.key()
        secret = "s/e+c'r$et"
        ui = FakeTerminal(
            answers=["s3.example.invalid", "AK", secret, "bucket", ""],
            confirms=[True],
        )
        self.assertEqual(self.run_setup(ui), 0, ui.text())
        self.assertIn("assuming https://", ui.text())
        self.assertIn("✓ 2 backup(s) found; newest is 2026-10-02", ui.text())
        self.assertIn(f"Wrote {REL}", ui.text())
        self.assertTrue(self.tracked())
        values = st.parse_env(self.decrypt())
        self.assertEqual(
            values,
            {
                "BACKUPS_URL": "https://s3.example.invalid",
                "BACKUPS_ACCESS_KEY": "AK",
                "BACKUPS_SECRET_KEY": secret,
                "BACKUPS_BUCKET": "bucket",
            },
        )
        # The product's check saw the credentials and the fetch command.
        seen = self.seen.read_text()
        self.assertIn("BACKUPS_BUCKET=bucket\n", seen)
        self.assertIn("FETCH=/stub/fetch\n", seen)
        self.assertEqual([q[2] for q in ui.asked], [False, False, True, False, False])

    def test_editing_prefills_keeps_the_secret_and_clears_a_prefix(self):
        self.key()
        first = FakeTerminal(
            answers=["https://a.invalid", "AK1", "SK1", "b1", "pre"], confirms=[False]
        )
        self.assertEqual(self.run_setup(first), 0, first.text())
        self.assertEqual(first.questions, ["Test these against the bucket now?"])

        # Enter on everything but the access key, and "-" on the prefix.
        second = FakeTerminal(answers=[None, "AK2", "", None, "-"], confirms=[False])
        self.assertEqual(self.run_setup(second), 0, second.text())
        self.assertIn("current values are pre-filled", second.text())
        self.assertIn("Keeping the stored secret key.", second.text())
        currents = [(header, current) for header, current, _, _ in second.asked]
        self.assertEqual(
            currents,
            [
                ("Endpoint URL", "https://a.invalid"),
                ("Access key ID", "AK1"),
                ("Secret access key", ""),
                ("Bucket", "b1"),
                ("Path inside the bucket (optional)", "pre"),
            ],
        )
        self.assertEqual(
            st.parse_env(self.decrypt()),
            {
                "BACKUPS_URL": "https://a.invalid",
                "BACKUPS_ACCESS_KEY": "AK2",
                "BACKUPS_SECRET_KEY": "SK1",
                "BACKUPS_BUCKET": "b1",
            },
        )

    def test_a_failing_check_asks_before_saving(self):
        self.key()
        ui = FakeTerminal(
            answers=["https://a.invalid", "AK", "SK", "bad", ""], confirms=[True, False]
        )
        self.assertEqual(self.run_setup(ui), 1)
        self.assertIn("Could not list the bucket:", ui.text())
        self.assertIn("Access Denied.", ui.text())
        self.assertEqual(ui.questions[-1], "Save anyway?")
        self.assertFalse((self.root / REL).exists())

        ui = FakeTerminal(
            answers=["https://a.invalid", "AK", "SK", "bad", ""], confirms=[True, True]
        )
        self.assertEqual(self.run_setup(ui), 0, ui.text())
        self.assertTrue((self.root / REL).exists())

    def test_a_secret_none_of_my_keys_reads_is_only_overwritten_on_request(self):
        self.key("alice")
        target = self.root / REL
        subprocess.run(
            [self.rage, "-e", "-r", BOB, "-o", str(target)],
            input=b"BACKUPS_URL=https://bob.invalid\n",
            check=True,
        )
        before = target.read_bytes()
        ui = FakeTerminal(confirms=[False])
        self.assertEqual(self.run_setup(ui), 1)
        self.assertIn("none of your keys can read it", ui.text())
        self.assertEqual(ui.questions, ["Overwrite it?"])
        self.assertEqual(target.read_bytes(), before)

    def test_a_required_answer_left_blank_stops(self):
        self.key()
        for answers, message in [
            ([""], "An endpoint is required."),
            (["https://a", ""], "An access key is required."),
            (["https://a", "AK", ""], "A secret key is required."),
            (["https://a", "AK", "SK", ""], "A bucket is required."),
        ]:
            ui = FakeTerminal(answers=answers)
            self.assertEqual(self.run_setup(ui), 1)
            self.assertIn(message, ui.text())
        self.assertFalse((self.root / REL).exists())


@unittest.skipUnless(SETUP_COMMAND, "no built setup-backup-access given")
class TerminalTest(unittest.TestCase):
    """The built command, at a (pseudo-)terminal: rich's prompts answer."""

    def test_through_a_pty(self):
        import fcntl
        import pty
        import termios

        tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, tmp)
        root = tmp / "project"
        (root / "secrets").mkdir(parents=True)
        home = tmp / "home"
        (home / ".ssh").mkdir(parents=True)
        shutil.copy(KEYS / "alice", home / ".ssh" / "id_ed25519")
        (home / ".ssh" / "id_ed25519").chmod(0o600)
        env = dict(
            os.environ,
            HOME=str(home),
            GIT_CONFIG_GLOBAL=str(tmp / "gitconfig"),
            GIT_CONFIG_SYSTEM="/dev/null",
            REPO_ROOT=str(root),
            NO_COLOR="1",
            TERM="xterm",
            COLUMNS="100",
        )
        subprocess.run(["git", "init", "-q", str(root)], check=True, env=env)

        master, slave = pty.openpty()

        def controlling_terminal():
            os.setsid()
            fcntl.ioctl(slave, termios.TIOCSCTTY, 0)

        proc = subprocess.Popen(
            [SETUP_COMMAND],
            stdin=slave,
            stdout=slave,
            stderr=slave,
            env=env,
            cwd=tmp,
            preexec_fn=controlling_terminal,  # noqa: PLW1509 (no threads here)
            close_fds=True,
        )
        os.close(slave)
        out = b""

        def expect(text: str, timeout: float = 60) -> None:
            nonlocal out
            deadline = time.monotonic() + timeout
            while text.encode() not in out:
                left = deadline - time.monotonic()
                if left <= 0:
                    self.fail(
                        f"waited for {text!r}; got:\n{out.decode(errors='replace')}"
                    )
                ready, _, _ = select.select([master], [], [], left)
                if ready:
                    try:
                        chunk = os.read(master, 4096)
                    except OSError:
                        chunk = b""
                    if not chunk:
                        self.fail(
                            f"ended before {text!r}:\n{out.decode(errors='replace')}"
                        )
                    out += chunk
            # Only what comes after a match counts towards the next one.
            out = out[out.index(text.encode()) + len(text) :]

        def send(line: str) -> None:
            time.sleep(0.2)
            os.write(master, (line + "\r").encode())

        for prompt, answer in [
            ("Endpoint URL", "https://s3.example.invalid"),
            ("Access key ID", "AK"),
            ("Secret access key", "SK'1"),
            ("Bucket", "bucket"),
            ("Path inside the bucket", ""),
            ("Test these against the bucket now?", "y"),
        ]:
            expect(prompt)
            send(answer)
        expect("backup(s) found")
        expect(f"Wrote {REL}")
        rest = b""
        while True:
            try:
                chunk = os.read(master, 4096)
            except OSError:
                break
            if not chunk:
                break
            rest += chunk
        os.close(master)
        self.assertEqual(proc.wait(timeout=60), 0, rest.decode(errors="replace"))
        plain = subprocess.run(
            ["rage", "--decrypt", "-i", str(KEYS / "alice"), str(root / REL)],
            check=True,
            capture_output=True,
            text=True,
        ).stdout
        self.assertEqual(
            st.parse_env(plain),
            {
                "BACKUPS_URL": "https://s3.example.invalid",
                "BACKUPS_ACCESS_KEY": "AK",
                "BACKUPS_SECRET_KEY": "SK'1",
                "BACKUPS_BUCKET": "bucket",
            },
        )


