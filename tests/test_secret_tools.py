"""python/secret_tools.py: the rules renderer, the env-file setup-backup-access
writes and reads back, the configuration schema, and setup-backup-access's
whole flow against a real ragenix, rage and git with the committed fixture
keys, its prompts answered by a stand-in for the terminal. With a built
setup-backup-access command as well, that command is driven once through a
pseudo-terminal, so rich's prompts are what answer.

Run: python -I tests/test_secret_tools.py <python/> <keys dir> [<setup-backup-access>]
     (an interpreter with rich; agenix, rage, git and bash on PATH)

The command runs as its own process, on the interpreter the product picks;
lib-secret-tools runs this on every interpreter the presets name, since the
products pick different ones.
"""

